import re


class SQLValidationError(Exception):
    """
    Raised when the generated SQL is invalid,
    unsafe or does not respect the project rules.
    """
    pass


class SQLValidator:
    """
    Validate SQL queries generated by the LLM.

    Responsibilities
    ----------------
    • Ensure the query is not empty
    • Allow only SELECT / WITH queries
    • Reject dangerous SQL keywords
    • Prevent multiple SQL statements
    • Ensure a valid SQL structure
    """

    FORBIDDEN_KEYWORDS = {

        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "TRUNCATE",
        "MERGE",
        "EXEC",
        "EXECUTE",

    }

    ALLOWED_PREFIXES = (

        "SELECT",

        "WITH",

    )

    # ==========================================================
    # PUBLIC
    # ==========================================================

    def validate(
        self,
        sql: str,
    ) -> str:
        """
        Validate a SQL query generated by the LLM.
        """

        sql = self._normalize(sql)

        self._check_empty(sql)

        self._check_special_response(sql)

        self._check_query_type(sql)

        self._check_multiple_statements(sql)

        self._check_forbidden_keywords(sql)

        self._check_contains_select(sql)

        self._check_contains_from(sql)

        return sql

    # ==========================================================
    # NORMALIZATION
    # ==========================================================

    def _normalize(
        self,
        sql: str,
    ) -> str:

        if sql is None:

            raise SQLValidationError(
                "Generated SQL is None."
            )

        sql = sql.strip()

        if sql.endswith(";"):

            sql = sql[:-1].strip()

        return sql

    # ==========================================================
    # VALIDATIONS
    # ==========================================================

    def _check_empty(
        self,
        sql: str,
    ):

        if sql == "":

            raise SQLValidationError(
                "Generated SQL is empty."
            )

    def _check_special_response(
        self,
        sql: str,
    ):

        if sql.upper() == "CANNOT_GENERATE_SQL":

            raise SQLValidationError(
                "The LLM could not generate SQL."
            )

    def _check_query_type(
        self,
        sql: str,
    ):

        upper = sql.upper()

        if not upper.startswith(
            self.ALLOWED_PREFIXES
        ):

            raise SQLValidationError(
                "Only SELECT or WITH statements are allowed."
            )

    def _check_multiple_statements(
        self,
        sql: str,
    ):

        if ";" in sql:

            raise SQLValidationError(
                "Multiple SQL statements are forbidden."
            )

    def _check_forbidden_keywords(
        self,
        sql: str,
    ):

        upper = sql.upper()

        for keyword in self.FORBIDDEN_KEYWORDS:

            if re.search(

                rf"\b{keyword}\b",

                upper,

            ):

                raise SQLValidationError(

                    f"Forbidden SQL keyword detected: {keyword}"

                )

    def _check_contains_select(
        self,
        sql: str,
    ):

        if re.search(

            r"\bSELECT\b",

            sql,

            flags=re.IGNORECASE,

        ) is None:

            raise SQLValidationError(
                "SELECT clause not found."
            )

    def _check_contains_from(
        self,
        sql: str,
    ):

        upper = sql.upper()

        # Certaines CTE peuvent commencer par WITH puis SELECT
        # mais une requête exploitable doit toujours contenir FROM.

        if "FROM" not in upper:

            raise SQLValidationError(
                "FROM clause not found."
            )


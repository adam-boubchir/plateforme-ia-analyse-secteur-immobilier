from __future__ import annotations

import re

__all__ = [
    "SQLValidationError",
    "SQLValidator",
]


FORBIDDEN_KEYWORDS: frozenset[str] = frozenset(
    {
        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "TRUNCATE",
        "MERGE",
        "EXEC",
        "EXECUTE",
    }
)

ALLOWED_PREFIXES: tuple[str, ...] = (
    "SELECT",
    "WITH",
)

CANNOT_GENERATE_SQL = "CANNOT_GENERATE_SQL"

SELECT_REGEX = re.compile(
    r"\bSELECT\b",
    re.IGNORECASE,
)


class SQLValidationError(Exception):
    """
    Raised when a generated SQL query
    does not satisfy the validation rules.
    """


class SQLValidator:
    """
    Validate SQL queries generated by the LLM.

    Responsibilities
    ----------------
    - Ensure the query is not empty.
    - Allow only SELECT / WITH statements.
    - Reject dangerous SQL keywords.
    - Prevent multiple SQL statements.
    - Ensure the query has a valid structure.
    """

    # ==========================================================
    # PUBLIC
    # ==========================================================

    def validate(
        self,
        sql: str,
    ) -> str:
        """
        Validate a SQL query generated by the LLM.
        """

        sql = self._normalize(sql)

        self._check_empty(sql)
        self._check_special_response(sql)
        self._check_query_type(sql)
        self._check_multiple_statements(sql)
        self._check_forbidden_keywords(sql)
        self._check_contains_select(sql)
        self._check_contains_from(sql)

        return sql

    # ==========================================================
    # PRIVATE
    # ==========================================================

    def _normalize(
        self,
        sql: str | None,
    ) -> str:
        """
        Normalize the SQL query before validation.
        """

        if sql is None:
            raise SQLValidationError(
                "Generated SQL is None."
            )

        return sql.removesuffix(";").strip()

    def _check_empty(
        self,
        sql: str,
    ) -> None:
        """
        Ensure the SQL query is not empty.
        """

        if not sql:
            raise SQLValidationError(
                "Generated SQL is empty."
            )

    def _check_special_response(
        self,
        sql: str,
    ) -> None:
        """
        Detect the special response returned by the LLM.
        """

        if sql.upper() == CANNOT_GENERATE_SQL:
            raise SQLValidationError(
                "The LLM could not generate SQL."
            )

    def _check_query_type(
        self,
        sql: str,
    ) -> None:
        """
        Ensure only SELECT or WITH statements are accepted.
        """

        if not sql.upper().startswith(ALLOWED_PREFIXES):
            raise SQLValidationError(
                "Only SELECT or WITH statements are allowed."
            )

    def _check_multiple_statements(
        self,
        sql: str,
    ) -> None:
        """
        Reject multiple SQL statements.
        """

        if ";" in sql:
            raise SQLValidationError(
                "Multiple SQL statements are forbidden."
            )

    def _check_forbidden_keywords(
        self,
        sql: str,
    ) -> None:
        """
        Reject dangerous SQL keywords.
        """

        upper = sql.upper()

        for keyword in FORBIDDEN_KEYWORDS:

            if re.search(
                rf"\b{keyword}\b",
                upper,
            ):
                raise SQLValidationError(
                    f"Forbidden SQL keyword detected: {keyword}"
                )

    def _check_contains_select(
        self,
        sql: str,
    ) -> None:
        """
        Ensure the query contains a SELECT clause.
        """

        if SELECT_REGEX.search(sql) is None:
            raise SQLValidationError(
                "SELECT clause not found."
            )

    def _check_contains_from(
        self,
        sql: str,
    ) -> None:
        """
        Ensure the query contains a FROM clause.
        """

        if "FROM" not in sql.upper():
            raise SQLValidationError(
                "FROM clause not found."
            )


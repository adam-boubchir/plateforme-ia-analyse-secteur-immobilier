import re


class SQLValidationError(Exception):
    """
    Raised when generated SQL is invalid or unsafe.
    """
    pass


class SQLValidator:
    """
    Validate SQL queries generated by the LLM.
    """

    FORBIDDEN_KEYWORDS = [
        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "TRUNCATE",
        "MERGE",
        "EXEC",
        "EXECUTE",
    ]

    def validate(
        self,
        sql: str,
    ) -> str:
        """
        Validate a generated SQL query.

        Returns:
            The cleaned SQL query.

        Raises:
            SQLValidationError
        """

        if sql is None:
            raise SQLValidationError(
                "Generated SQL is None."
            )

        sql = sql.strip()

        if sql == "":
            raise SQLValidationError(
                "Generated SQL is empty."
            )

        if sql.upper() == "CANNOT_GENERATE_SQL":
            raise SQLValidationError(
                "The model could not generate SQL."
            )

        sql_upper = sql.upper()

        if not sql_upper.startswith("SELECT"):
            raise SQLValidationError(
                "Only SELECT statements are allowed."
            )

        for keyword in self.FORBIDDEN_KEYWORDS:

            if re.search(
                rf"\b{keyword}\b",
                sql_upper,
            ):

                raise SQLValidationError(
                    f"Forbidden SQL keyword detected: {keyword}"
                )

        sql_without_semicolon = sql.rstrip()

        if sql_without_semicolon.endswith(";"):
            sql_without_semicolon = sql_without_semicolon[:-1]

        if ";" in sql_without_semicolon:
            raise SQLValidationError(
                "Multiple SQL statements are not allowed."
            )

        if " FROM " not in sql_upper:
            raise SQLValidationError(
                "SQL query must contain a FROM clause."
            )

        return sql
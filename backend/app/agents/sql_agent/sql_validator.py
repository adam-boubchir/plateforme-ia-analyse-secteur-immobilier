import re


class SQLValidationError(Exception):
    """
    Raised when generated SQL is invalid or unsafe.
    """
    pass


class SQLValidator:
    """
    Validate SQL queries generated by the LLM.
    """

    FORBIDDEN_KEYWORDS = [
        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "TRUNCATE",
        "MERGE",
        "EXEC",
        "EXECUTE",
    ]

    def validate(
        self,
        sql: str,
    ) -> str:
        """
        Validate a generated SQL query.

        Returns:
            Clean SQL query.

        Raises:
            SQLValidationError
        """

        if sql is None:
            raise SQLValidationError(
                "Generated SQL is None."
            )

        sql = sql.strip()

        if sql == "":
            raise SQLValidationError(
                "Generated SQL is empty."
            )

        if sql.upper() == "CANNOT_GENERATE_SQL":
            raise SQLValidationError(
                "The model could not generate SQL."
            )

        # Remove trailing semicolon
        sql = sql.rstrip()

        if sql.endswith(";"):
            sql = sql[:-1].rstrip()

        sql_upper = sql.upper()

        # Only SELECT queries or CTEs beginning with WITH are allowed
        if not (
            sql_upper.startswith("SELECT")
            or sql_upper.startswith("WITH")
        ):
            raise SQLValidationError(
                "Only SELECT statements are allowed."
            )

        # Reject dangerous keywords
        for keyword in self.FORBIDDEN_KEYWORDS:

            if re.search(
                rf"\b{keyword}\b",
                sql_upper,
            ):
                raise SQLValidationError(
                    f"Forbidden SQL keyword detected: {keyword}"
                )

        # Prevent multiple SQL statements
        if ";" in sql:
            raise SQLValidationError(
                "Multiple SQL statements are not allowed."
            )

        # A valid SELECT/CTE must eventually contain SELECT
        if not re.search(r"\bSELECT\b", sql_upper):
            raise SQLValidationError(
                "Missing SELECT statement."
            )

        # It must also contain FROM
        if not re.search(r"\bFROM\b", sql_upper):
            raise SQLValidationError(
                "SQL query must contain a FROM clause."
            )

        return sql
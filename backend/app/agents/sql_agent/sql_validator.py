from __future__ import annotations

import re

__all__ = (
    "SQLValidationError",
    "SQLValidator",
)

# ==========================================================
# CONSTANTS
# ==========================================================

_FORBIDDEN_KEYWORDS: frozenset[str] = frozenset(
    {
        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "TRUNCATE",
        "MERGE",
        "EXEC",
        "EXECUTE",
    }
)

_FORBIDDEN_REGEX: dict[str, re.Pattern[str]] = {
    keyword: re.compile(
        rf"\b{keyword}\b",
        re.IGNORECASE,
    )
    for keyword in _FORBIDDEN_KEYWORDS
}

_ALLOWED_PREFIXES = (
    "SELECT",
    "WITH",
)

_SPECIAL_RESPONSE_CANNOT_GENERATE_SQL = "CANNOT_GENERATE_SQL"

_SELECT_REGEX = re.compile(
    r"\bSELECT\b",
    re.IGNORECASE,
)


class SQLValidationError(Exception):
    """
    Raised when a generated SQL query does not satisfy the validation rules.
    """


class SQLValidator:
    """
    Validate SQL queries generated by the language model.

    Responsibilities
    ----------------
    - Validate query type.
    - Reject dangerous statements.
    - Ensure mandatory SQL clauses exist.
    - Return a normalized SQL query.
    """

    # ==========================================================
    # PUBLIC
    # ==========================================================

    def validate(
        self,
        *,
        sql: str,
    ) -> str:
        """
        Validate a SQL query.

        Args:
            sql:
                SQL query generated by the LLM.

        Returns:
            Normalized SQL query.

        Raises:
            SQLValidationError:
                If one of the validation rules fails.
        """

        normalized_sql = self._normalize(
            sql=sql,
        )

        upper_sql = normalized_sql.upper()

        self._check_empty(
            sql=normalized_sql,
        )

        self._check_special_response(
            upper_sql=upper_sql,
        )

        self._check_query_type(
            upper_sql=upper_sql,
        )

        self._check_multiple_statements(
            sql=normalized_sql,
        )

        self._check_forbidden_keywords(
            upper_sql=upper_sql,
        )

        self._check_contains_select(
            sql=normalized_sql,
        )

        self._check_contains_from(
            upper_sql=upper_sql,
        )

        return normalized_sql

    # ==========================================================
    # PRIVATE
    # ==========================================================

    @staticmethod
    def _normalize(
        *,
        sql: str | None,
    ) -> str:
        """
        Normalize a SQL query.
        """

        if sql is None:
            raise SQLValidationError(
                "Generated SQL is None."
            )

        normalized_sql = sql.removesuffix(
            ";",
        ).strip()

        return normalized_sql

    @staticmethod
    def _check_empty(
        *,
        sql: str,
    ) -> None:
        """
        Ensure the SQL query is not empty.
        """

        if not sql:
            raise SQLValidationError(
                "Generated SQL is empty."
            )

    @staticmethod
    def _check_special_response(
        *,
        upper_sql: str,
    ) -> None:
        """
        Reject the special response returned by the LLM.
        """

        if upper_sql == _SPECIAL_RESPONSE_CANNOT_GENERATE_SQL:
            raise SQLValidationError(
                "The LLM could not generate SQL."
            )

    @staticmethod
    def _check_query_type(
        *,
        upper_sql: str,
    ) -> None:
        """
        Ensure the query starts with SELECT or WITH.
        """

        if not upper_sql.startswith(
            _ALLOWED_PREFIXES,
        ):
            raise SQLValidationError(
                "Only SELECT or WITH statements are allowed."
            )

    @staticmethod
    def _check_multiple_statements(
        *,
        sql: str,
    ) -> None:
        """
        Prevent execution of multiple SQL statements.
        """

        if ";" in sql:
            raise SQLValidationError(
                "Multiple SQL statements are forbidden."
            )

    @staticmethod
    def _check_forbidden_keywords(
        *,
        upper_sql: str,
    ) -> None:
        """
        Reject dangerous SQL keywords.
        """

        for keyword, pattern in _FORBIDDEN_REGEX.items():

            if pattern.search(
                upper_sql,
            ):
                raise SQLValidationError(
                    f"Forbidden SQL keyword detected: {keyword}"
                )

    @staticmethod
    def _check_contains_select(
        *,
        sql: str,
    ) -> None:
        """
        Ensure the query contains a SELECT clause.
        """

        if _SELECT_REGEX.search(
            sql,
        ) is None:
            raise SQLValidationError(
                "SELECT clause not found."
            )

    @staticmethod
    def _check_contains_from(
        *,
        upper_sql: str,
    ) -> None:
        """
        Ensure the query contains a FROM clause.
        """

        if "FROM" not in upper_sql:
            raise SQLValidationError(
                "FROM clause not found."
            )


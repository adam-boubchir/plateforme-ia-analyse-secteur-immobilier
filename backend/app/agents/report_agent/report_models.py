from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any

from app.visualization.models import ChartRecommendation


__all__ = (
    "ReportType",
    "ReportRequest",
    "DatasetMetadata",
    "NumericStatistic",
    "ReportStatistics",
    "Insight",
    "ReportAnalysis",
    "ReportSection",
    "ReportResult",
)


# ==========================================================
# ENUMS
# ==========================================================


class ReportType(str, Enum):
    """
    High-level report categories produced by the Report Agent.
    """

    SUMMARY = "summary"
    COMPARISON = "comparison"
    TREND = "trend"
    DISTRIBUTION = "distribution"
    DETAIL = "detail"
    STATISTICAL = "statistical"
    CUSTOM = "custom"


# ==========================================================
# REQUEST
# ==========================================================


@dataclass(slots=True)
class ReportRequest:
    """
    Input received by the Report Agent.
    """

    question: str
    sql: str
    rows: list[dict[str, Any]]

    generated_at: datetime = field(
        default_factory=datetime.utcnow,
    )

    author: str | None = None

    conversation_id: int | None = None

    generated_by: str = "ReportAgent"


# ==========================================================
# DATASET METADATA
# ==========================================================


@dataclass(slots=True)
class DatasetMetadata:
    """
    Metadata extracted from the SQL result set.
    """

    row_count: int

    column_count: int

    columns: list[str]

    numeric_columns: list[str]

    categorical_columns: list[str]

    datetime_columns: list[str]

    geographic_columns: list[str] = field(
        default_factory=list,
    )

    null_columns: list[str] = field(
        default_factory=list,
    )

    unique_values: dict[str, int] = field(
        default_factory=dict,
    )

    sample_size: int = 0


# ==========================================================
# STATISTICS
# ==========================================================


@dataclass(slots=True)
class NumericStatistic:
    """
    Statistical summary for one numeric column.
    """

    column: str

    minimum: float | None

    maximum: float | None

    average: float | None

    median: float | None

    std: float | None

    total: float | None

    count: int

    variance: float | None

    q1: float | None

    q3: float | None

    missing_values: int


@dataclass(slots=True)
class ReportStatistics:
    """
    Collection of computed statistics.
    """

    statistics: list[NumericStatistic] = field(
        default_factory=list,
    )


# ==========================================================
# INSIGHTS
# ==========================================================


@dataclass(slots=True)
class Insight:
    """
    Business insight extracted from the dataset.
    """

    title: str

    description: str

    severity: str = "info"


# ==========================================================
# ANALYSIS
# ==========================================================


@dataclass(slots=True)
class ReportAnalysis:
    """
    Structured analysis produced before report generation.
    """

    report_type: ReportType

    dataset: DatasetMetadata

    statistics: ReportStatistics

    insights: list[Insight] = field(
        default_factory=list,
    )

    chart_count: int = 0


# ==========================================================
# REPORT
# ==========================================================


@dataclass(slots=True)
class ReportSection:
    """
    One section of the generated report.
    """

    title: str

    content: str

    order: int = 0


@dataclass(slots=True)
class ReportResult:
    """
    Final report generated by the Report Agent.
    """

    title: str

    executive_summary: str

    objective: str

    methodology: str

    markdown: str

    conclusions: list[str]

    recommendations: list[str]

    sections: list[ReportSection]

    charts: list[ChartRecommendation] = field(
        default_factory=list,
    )

    pdf_path: str | None = None

    generated_at: datetime = field(
        default_factory=datetime.utcnow,
    )

    row_count: int = 0

    column_count: int = 0